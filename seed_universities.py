def run(dry_run=False):
    uni_count = 0; gs_count = 0

    for pool, uni_type in [(NATIONAL, "国立"), (PUBLIC, "公立"), (PRIVATE, "私立")]:
        for name, name_jp, location, gs_list in pool:
            if dry_run:
                uni_count += 1; gs_count += len(gs_list)
                continue

            r = supabase.table("universities").upsert({
                "name": name, "name_jp": name_jp, "type": uni_type,
                "location": location,
            }, on_conflict="name").execute()
            uni_id = r.data[0]["id"]

            for gs_name in gs_list:
                supabase.table("graduate_schools").upsert({
                    "university_id": uni_id,
                    "name": gs_name, "name_jp": gs_name,
                }, on_conflict="university_id,name").execute()
                gs_count += 1
            uni_count += 1
            print(f"  {uni_type[:2]} {name}")

    print(f"\nSeeded: {uni_count} universities, {gs_count} graduate schools")
    if dry_run:
        print("(DRY RUN — no writes)")
        print(f"  National: {len(NATIONAL)} / Public: {len(PUBLIC)} / Private: {len(PRIVATE)}")


if __name__ == "__main__":
    dry = "--dry-run" in sys.argv
    run(dry_run=dry)
